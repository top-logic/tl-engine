package com.top_logic.element.model.generate;

import static com.top_logic.model.util.TLModelNamingConvention.*;

import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.lang.reflect.WildcardType;
import java.util.ArrayList;
import java.util.Collection;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;

import com.top_logic.basic.Protocol;
import com.top_logic.element.meta.kbbased.AttributedWrapper;
import com.top_logic.model.TLClass;
import com.top_logic.model.TLStructuredTypePart;
import com.top_logic.model.TLType;
import com.top_logic.model.config.JavaName;
import com.top_logic.model.util.TLModelUtil;

/**
 * Check that the access methods generated by an {@link InterfaceGenerator} do not clash with
 * methods the generated interface or the implementation class inherits.
 *
 * <p>
 * A generated access method clashes with an inherited method of the same signature, if
 * </p>
 * <ul>
 * <li>the return types are incompatible,</li>
 * <li>the inherited method is declared in a class of the implementation base class (it would hide
 * the generated default method, or prevent compiling it), or</li>
 * <li>the implementation base class inherits the method from an interface that the generated
 * interface does not extend (the implementation class would inherit unrelated methods).</li>
 * </ul>
 *
 * <p>
 * Parts overriding another part are not checked, since their access methods override the access
 * methods of the overridden part. Types generated in the same run are not loadable; for those, the
 * check uses the loadable types of their generalizations.
 * </p>
 *
 * @author <a href="mailto:bhu@top-logic.com">Bernhard Haumacher</a>
 */
public class AccessorClashCheck {

	private final Protocol _log;

	private final ClassLoader _classLoader;

	private final Map<String, Optional<Class<?>>> _classes = new HashMap<>();

	/**
	 * Creates a {@link AccessorClashCheck}.
	 *
	 * @param log
	 *        The {@link Protocol} to report clashes to.
	 * @param classLoader
	 *        The {@link ClassLoader} to load the inherited types from.
	 */
	public AccessorClashCheck(Protocol log, ClassLoader classLoader) {
		_log = log;
		_classLoader = classLoader;
	}

	/**
	 * Reports each access method of the given generator that clashes with an inherited method as
	 * error.
	 *
	 * @param generator
	 *        The generator of the interface to check.
	 * @param checkImplementation
	 *        Whether the implementation class is generated, too, so that the methods of its base
	 *        class must also be checked.
	 */
	public void check(InterfaceGenerator generator, boolean checkImplementation) {
		if (!(generator.type() instanceof TLClass)) {
			return;
		}
		TLClass type = (TLClass) generator.type();
		Set<Class<?>> superInterfaces = superInterfaces(type);
		Class<?> baseClass = checkImplementation ? implementationBaseClass(type) : null;

		for (TLStructuredTypePart part : generator.accessorParts()) {
			if (part.isOverride()) {
				continue;
			}
			for (GeneratedAccessor accessor : generator.accessors(part)) {
				checkAccessor(type, accessor, superInterfaces, baseClass);
			}
		}
	}

	private void checkAccessor(TLClass type, GeneratedAccessor accessor, Set<Class<?>> superInterfaces,
			Class<?> baseClass) {
		for (Class<?> superInterface : superInterfaces) {
			for (Method method : superInterface.getMethods()) {
				if (Modifier.isStatic(method.getModifiers()) || !sameSignature(accessor, method)) {
					continue;
				}
				if (!compatibleReturnType(accessor, method)) {
					reportClash(type, accessor, method, "the return types are incompatible");
					return;
				}
			}
		}
		if (baseClass == null) {
			return;
		}
		for (Method method : baseClassMethods(baseClass)) {
			if (!sameSignature(accessor, method)) {
				continue;
			}
			Class<?> declaringClass = method.getDeclaringClass();
			if (!declaringClass.isInterface()) {
				reportClash(type, accessor, method, "the method is declared in a class the implementation class '"
					+ implementationName(type) + "' inherits from");
				return;
			}
			if (Modifier.isStatic(method.getModifiers())) {
				continue;
			}
			if (!compatibleReturnType(accessor, method)) {
				reportClash(type, accessor, method, "the return types are incompatible");
				return;
			}
			if (!isExtended(declaringClass, superInterfaces)) {
				reportClash(type, accessor, method, "the implementation class '" + implementationName(type)
					+ "' inherits the method from an interface the generated interface does not extend");
				return;
			}
		}
	}

	private void reportClash(TLClass type, GeneratedAccessor accessor, Method method, String reason) {
		_log.error("Generated method '" + accessor + "' for attribute '" + accessor.getPart().getName()
			+ "' of type '" + TLModelUtil.qualifiedName(type) + "' clashes with method '" + method.toGenericString()
			+ "' declared in '" + method.getDeclaringClass().getName() + "': " + reason
			+ ". Choose a different Java name for the attribute with the annotation <" + JavaName.TAG_NAME + " "
			+ JavaName.VALUE + "=\"...\"/>.");
	}

	/**
	 * All public methods of the given class and the non-public, non-private methods declared in its
	 * class hierarchy.
	 */
	private static Collection<Method> baseClassMethods(Class<?> baseClass) {
		List<Method> result = new ArrayList<>();
		for (Method method : baseClass.getMethods()) {
			result.add(method);
		}
		for (Class<?> current = baseClass; current != null; current = current.getSuperclass()) {
			for (Method method : current.getDeclaredMethods()) {
				int modifiers = method.getModifiers();
				if (Modifier.isPublic(modifiers) || Modifier.isPrivate(modifiers) || method.isSynthetic()) {
					continue;
				}
				result.add(method);
			}
		}
		return result;
	}

	private static boolean isExtended(Class<?> anInterface, Set<Class<?>> superInterfaces) {
		for (Class<?> superInterface : superInterfaces) {
			if (anInterface.isAssignableFrom(superInterface)) {
				return true;
			}
		}
		return false;
	}

	private static boolean sameSignature(GeneratedAccessor accessor, Method method) {
		if (!accessor.getName().equals(method.getName())) {
			return false;
		}
		List<String> parameterTypes = accessor.getParameterTypes();
		Class<?>[] methodParameters = method.getParameterTypes();
		if (parameterTypes.size() != methodParameters.length) {
			return false;
		}
		for (int n = 0; n < methodParameters.length; n++) {
			if (!isNamed(methodParameters[n], parameterTypes.get(n))) {
				return false;
			}
		}
		return true;
	}

	private static boolean isNamed(Class<?> type, String name) {
		return name.equals(type.getName()) || name.equals(type.getCanonicalName());
	}

	private boolean compatibleReturnType(GeneratedAccessor accessor, Method method) {
		Class<?> inheritedType = method.getReturnType();
		String returnType = accessor.getReturnType();
		if (inheritedType.isPrimitive() || isPrimitive(returnType)) {
			return isNamed(inheritedType, returnType);
		}
		TLType valueType = accessor.getElementType() == null ? accessor.getValueType() : null;
		if (!isSubtype(returnType, valueType, inheritedType)) {
			return false;
		}
		if (accessor.getElementType() == null) {
			return true;
		}
		Type genericType = method.getGenericReturnType();
		if (!(genericType instanceof ParameterizedType)) {
			return true;
		}
		Type[] typeArguments = ((ParameterizedType) genericType).getActualTypeArguments();
		if (!Collection.class.isAssignableFrom(inheritedType) || typeArguments.length != 1) {
			return true;
		}
		return containsElementType(accessor, typeArguments[0]);
	}

	/**
	 * Whether the given type argument of an inherited collection type contains the element type of
	 * the generated collection type.
	 */
	private boolean containsElementType(GeneratedAccessor accessor, Type typeArgument) {
		if (typeArgument instanceof Class<?>) {
			return !accessor.isElementWildcard() && isNamed((Class<?>) typeArgument, accessor.getElementType());
		}
		if (typeArgument instanceof ParameterizedType) {
			// The generated element type is never parameterized.
			return false;
		}
		if (typeArgument instanceof WildcardType) {
			WildcardType wildcard = (WildcardType) typeArgument;
			if (wildcard.getLowerBounds().length > 0) {
				return !accessor.isElementWildcard();
			}
			Type[] upperBounds = wildcard.getUpperBounds();
			if (upperBounds.length == 1 && upperBounds[0] instanceof Class<?>) {
				return isSubtype(accessor.getElementType(), accessor.getValueType(), (Class<?>) upperBounds[0]);
			}
		}
		// Type variables and complex bounds are not checked.
		return true;
	}

	/**
	 * Whether the type with the given name is a subtype of the given class.
	 *
	 * @param typeName
	 *        The name of the type to check.
	 * @param modelType
	 *        The model type, the Java type with the given name represents, <code>null</code> if
	 *        not known. It is used to determine the loadable super types of a type that is
	 *        generated in the same run.
	 * @param superType
	 *        The potential super type.
	 */
	private boolean isSubtype(String typeName, TLType modelType, Class<?> superType) {
		if (superType == Object.class) {
			return true;
		}
		Class<?> type = load(typeName);
		if (type != null) {
			return superType.isAssignableFrom(type);
		}
		if (!(modelType instanceof TLClass)) {
			// Not decidable.
			return true;
		}
		Set<Class<?>> loadableSuperTypes = superInterfaces((TLClass) modelType);
		if (loadableSuperTypes.isEmpty()) {
			// Not decidable.
			return true;
		}
		return isExtended(superType, loadableSuperTypes);
	}

	private static boolean isPrimitive(String typeName) {
		return GeneratedAccessor.VOID.equals(typeName) || BaseClassGenerator.isPrimitiveName(typeName);
	}

	/**
	 * The loadable interfaces the generated interface of the given type extends.
	 *
	 * <p>
	 * The interface of a generalization that is not loadable (since it is generated in the same
	 * run) is replaced by the loadable interfaces of its own generalizations.
	 * </p>
	 */
	private Set<Class<?>> superInterfaces(TLClass type) {
		Set<Class<?>> result = new LinkedHashSet<>();
		addSuperInterfaces(result, new HashSet<>(), type.getGeneralizations());
		return result;
	}

	private void addSuperInterfaces(Set<Class<?>> result, Set<TLClass> seen, List<TLClass> generalizations) {
		for (TLClass generalization : generalizations) {
			if (!seen.add(generalization)) {
				continue;
			}
			String interfaceName = interfaceName(generalization);
			Class<?> loadedInterface = interfaceName == null ? null : load(interfaceName);
			if (loadedInterface != null) {
				result.add(loadedInterface);
			} else {
				addSuperInterfaces(result, seen, generalization.getGeneralizations());
			}
		}
	}

	/**
	 * The loadable class the implementation class of the given type extends (directly or through
	 * implementation classes generated in the same run).
	 */
	private Class<?> implementationBaseClass(TLClass type) {
		TLClass superType = ImplementationTemplateGenerator.implementationSuperType(type);
		while (superType != null) {
			Class<?> loadedClass = load(implementationName(superType));
			if (loadedClass != null) {
				return loadedClass;
			}
			superType = ImplementationTemplateGenerator.implementationSuperType(superType);
		}
		return AttributedWrapper.class;
	}

	private Class<?> load(String className) {
		return _classes.computeIfAbsent(className, name -> Optional.ofNullable(loadClass(name))).orElse(null);
	}

	private Class<?> loadClass(String className) {
		String binaryName = className;
		while (true) {
			try {
				return Class.forName(binaryName, false, _classLoader);
			} catch (ClassNotFoundException | LinkageError ex) {
				// Try to resolve as nested class.
				int lastDot = binaryName.lastIndexOf('.');
				if (lastDot < 0) {
					return null;
				}
				binaryName = binaryName.substring(0, lastDot) + '$' + binaryName.substring(lastDot + 1);
			}
		}
	}

}
