// Erzeugt dist/ und src/main/webapp/style/tl-design-system/ aus src/ (beide nicht eingecheckt, beide gleich).
// Was hier nicht herauskommt, gibt es im Design System nicht.
import { resolve, primitives } from './resolve.mjs';
import { dtcg } from './dtcg.mjs';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Alle CSS-Dateien unter src/components/, rekursiv, sortiert nach Pfad. Name relativ mit '/'. */
export function componentSources(dirUrl) {
  const root = fileURLToPath(dirUrl);
  const files = [];
  (function walk(dir) {
    for (const entry of readdirSync(dir).sort()) {
      const p = join(dir, entry);
      if (statSync(p).isDirectory()) walk(p);
      else if (entry.endsWith('.css')) files.push(p);
    }
  })(root);
  return files.sort().map((p) => ({ name: relative(root, p).split(sep).join('/'), css: readFileSync(p, 'utf8') }));
}

// Rollenregeln: Pill, Avatar, Alert, Chip und Segment lesen je Rolle dieselben zwei Tokens, Fläche und
// Linie. Statt sie in jeder Datei auszuschreiben, steht dort ein Marker-Kommentar
// `/* @tl-roles: <art> <.tl-ziel> */`, und hier entsteht je Rolle aus src/tokens.json eine Regel
// `<ziel>[data-tl-role="<rolle>"]` — die Tönung ist ein Attribut, kein Modifier (3b §11, W7); eine neue
// Kategorie ist eine Zeile in tokens.json, nicht fünf. Ziel ist ein Block (tl-chip) oder ein Element
// (tl-segmented__segment), nie ein Modifier. Kommentar, damit Klassen-Gate und Tests auf src/ ihn
// überlesen. docs/skalen.md „Gleiches wird zusammengelegt“. In `:where(<ziel>)` gesetzt, erzeugt der Marker
// die Regeln ohne Spezifität: für ein Ablage-Ziel, dessen Fläche das Ablegen übermalt (Tabellenzeile, #29815).
// Je Rolle eine Deklarationsliste: Fläche und Linie für die getönten Arten; die gefüllte Kategorie (5c §4) liest
// ihre Fläche und die gerechnete Schrift darauf (category-surface, gefüllter Termin) oder nur die Fläche
// (category-fill, Punkt ohne Text).
const flaecheLinie = (flaeche, linie) => `background: var(--tl-${flaeche}); border-color: var(--tl-${linie});`;
const gefuellt = (T) => Object.keys(T.color.light).map((n) => /^(category-\d+)-surface$/.exec(n)?.[1])
  .filter((r) => r && `text-on-${r}` in T.derived.light);
const ROLLEN = {
  brand: () => [['brand', flaecheLinie('surface-brand-subtle', 'border-interactive')]],
  category: (T) => Object.keys(T.color.light).map((n) => /^(category-\d+)-subtle$/.exec(n)?.[1])
    .filter((r) => r && `${r}-border` in T.color.light).map((r) => [r, flaecheLinie(`${r}-subtle`, `${r}-border`)]),
  status: (T) => Object.keys(T.color.light).map((n) => /^status-([a-z]+)-subtle$/.exec(n)?.[1])
    .filter((s) => s && `status-${s}-border` in T.color.light).map((s) => [s, flaecheLinie(`status-${s}-subtle`, `status-${s}-border`)]),
  'category-surface': (T) => gefuellt(T).map((r) => [r, `background: var(--tl-${r}-surface); color: var(--tl-text-on-${r});`]),
  'category-fill': (T) => gefuellt(T).map((r) => [r, `background: var(--tl-${r}-surface);`]),
};
const MARKER = /\/\*\s*@tl-roles:\s*(\S+)\s+(\S+)\s*\*\//g;
const ZIEL = /^\.tl-[a-z0-9]+(-[a-z0-9]+)*(__[a-z0-9]+(-[a-z0-9]+)*)?$/;

/** Ersetzt jeden Marker `/* @tl-roles: <art> <.tl-ziel> *\/` durch die Rollenregeln aus T. */
export function expandRoles(css, T) {
  return css.replace(MARKER, (_, art, sel) => {
    if (!ROLLEN[art]) throw new Error(`@tl-roles: unbekannte Rollenart ${art} (bekannt: ${Object.keys(ROLLEN).join(', ')})`);
    const ohne = /^:where\((.*)\)$/.exec(sel);
    const ziel = ohne ? ohne[1] : sel;
    if (!ZIEL.test(ziel)) throw new Error(`@tl-roles: ${sel} ist weder Block- noch Elementklasse`);
    return ROLLEN[art](T).map(([rolle, deklarationen]) => {
      const auswahl = `${ziel}[data-tl-role="${rolle}"]`;
      return `${ohne ? `:where(${auswahl})` : auswahl} { ${deklarationen} }`;
    }).join('\n');
  });
}

function componentsCss(components, T) {
  return `${HERKUNFT}/* Components, one section per file under src/components/. */\n\n`
    + components.map((c) => `/* --- ${c.name} --- */\n${expandRoles(c.css, T).trimEnd()}\n`).join('\n');
}

const REF = /^\{([a-z0-9-]+)\}$/;
const line = (n, v) => `  --tl-${n}: ${v};`;
const asVar = (v) => { const m = REF.exec(String(v)); return m ? `var(--tl-${m[1]})` : v; };
const block = (o) => Object.entries(o).filter(([k]) => !k.startsWith('_')).map(([n, v]) => line(n, asVar(v))).join('\n');
// Jede erzeugte Datei nennt ihre Herkunft: Sie entsteht beim Build und ist nicht eingecheckt, und wer sie in
// target/ oder im Webapp-Ordner findet, soll wissen, wo die Quelle liegt und dass er hier nichts ändert.
const HERKUNFT = `/* Generated by tl-design-system (src/, tools/generate.mjs) during the build.
   Do not edit — edit the source. */\n`;
const HEAD = `${HERKUNFT}\n`;

function primitivesCss(P) {
  return `${HEAD}/* Schicht 1: Primitive. Reine Werte ohne Bedeutung — die Stelle, an der ein
   Kundenprojekt eingreift. Wer hier einen Wert überschreibt, ändert jede Rolle mit. */
:root {
${block(primitives(P))}
}
`;
}

function tokensCss(P, T, R) {
  const derived = (mode) => Object.entries(R.derived[mode]).map(([n, v]) => line(n, v)).join('\n');
  return `${HEAD}/* Schicht 2: Rollen. Jede verweist auf eine Primitive, keine trägt einen Wert.
   Ausnahme: Beschriftungen auf Flächen (--tl-text-on-*, --tl-icon-on-*) sind gerechnet. */
:root,
[data-tl-mode="light"] {
  color-scheme: light;
${block(T.measure)}
${block(T.layer)}

${block(T.color.light)}
${derived('light')}

${block(T.effect.light)}

${block(T.density.normal)}
}

[data-tl-mode="dark"] {
  color-scheme: dark;
${block(T.color.dark)}
${derived('dark')}

${block(T.effect.dark)}
}

[data-tl-density="compact"] {
${block(T.density.compact)}
}
`;
}

function baseCss(T) {
  // Fließtext vom Server (tl-prose, Spec 5b §5) bekommt seine Schrift aus den Typo-Klassen: die Prose-Selektoren
  // stehen vor der Klasse in derselben Regel, je auf eigener Zeile. Vorangestellt, nicht angehängt — die Regel
  // endet weiter mit `.tl-type-<n> {`.
  const prose = (n) => ((T.prose ?? {})[n] ?? []).map((el) => `.tl-prose ${el},\n`).join('');
  const type = Object.entries(T.type).filter(([k]) => !k.startsWith('_')).map(([n, k]) => `${prose(n)}.tl-type-${n} {
  font-family: var(--tl-font-family-${k.family});
  font-size: var(--tl-font-size-${k.size});
  font-weight: ${k.weight};
  line-height: ${k.lineHeight};
  letter-spacing: ${k.tracking};
}`).join('\n\n');
  const print = Object.entries(T.print).map(([n, k]) => `  .tl-print-${n} {
    font-size: ${k.size};
    font-weight: ${k.weight};
    line-height: ${k.lineHeight};
  }`).join('\n');
  return `${HEAD}/* Grundklassen. Jede liest nur Variablen. */
html {
  -webkit-text-size-adjust: 100%;
}

body {
  margin: 0;
  background: var(--tl-surface-base);
  color: var(--tl-text-primary);
  font-family: var(--tl-font-family-sans);
}

*, *::before, *::after {
  box-sizing: border-box;
}

/* Typografie: eine Größe ist keine Klasse. Die Klasse legt alles fest. */
${type}

/* Zahlen in Spalten fluchten nur mit tabellarischen Ziffern. Pflicht, nicht Option. */
.tl-nums {
  font-feature-settings: "tnum" 1, "zero" 1;
  font-variant-numeric: tabular-nums slashed-zero;
}

/* Sichtbar nur für Screenreader: das Clipping verbirgt das Element, die absolute Lage nimmt es aus
   dem Fluss, die Box von size-hidden hält einen langen Text davon ab, einen Rollbalken zu erzeugen —
   1 px statt 0, damit Screenreader das Element nicht als leer überspringen. inset(50%) ist ein
   Anteil, kein Maß, und darum kein Versehen. Ersetzt tlVisuallyHidden des Altbestands. */
.tl-visually-hidden {
  position: absolute;
  width: var(--tl-size-hidden);
  height: var(--tl-size-hidden);
  overflow: hidden;
  clip-path: inset(50%);
  white-space: nowrap;
  margin: 0;
  padding: 0;
  border: 0;
}

/* Der Ring gehört der Tastatur. Ein Mechanismus, außen, nur beim Tastaturfokus.
   Ein Behälter mit virtuellem Cursor (Tabelle, Baum: aria-activedescendant, 3a §5.4, 3b §3) trägt ihn
   nicht selbst: der Ring liegt innen am Element mit data-tl-state~="cursor". Gezeichnet wird er von
   dessen ::after, einer Fläche über dem Element — haftende Zellen überdecken den eigenen Umriss einer
   Zeile. Ein Feld mit aria-activedescendant ist kein Behälter und behält den Ring: das Suchfeld eines
   Select (input) und das Select ohne Suchfeld (role=combobox) — ihr Cursor steht im Popup.
   Eine Dashboard-Kachel mit Aktion trägt den Ring, wenn ihr verborgener Knopf (tl-visually-hidden) den Tastaturfokus
   hat: der Knopf ist unsichtbar, die Kachel ist, was der Nutzer drückt (Spec 5c §6).
   Die hervorgehobene Option einer Select-Liste ist die Tastaturposition (der Fokus bleibt im Feld, aria-activedescendant):
   ihr ::after trägt den Ring, innen, wie das Cursor-Element — kein zweiter Ring in der Komponente. */
:where(a, button, input, select, textarea, summary, [tabindex], [contenteditable]):where(:not(:not(input, textarea, [role="combobox"])[aria-activedescendant])):focus-visible,
:where(:not(input, textarea, [role="combobox"])[aria-activedescendant]:focus-visible [data-tl-state~="cursor"])::after,
.tl-dashboard__tile:has(> .tl-dashboard__action:focus-visible),
.tl-select__option[data-tl-state~="highlighted"]::after {
  outline: var(--tl-focus-width) solid var(--tl-focus-ring);
  outline-offset: var(--tl-focus-offset);
}

/* Die Fläche des Cursor-Rings: deckungsgleich mit dem Element, über seinen haftenden Zellen
   (layer-sticky; der Behälter isoliert den Stapel), für den Zeiger durchlässig, der Ring nach innen. */
:where(:not(input, textarea, [role="combobox"])[aria-activedescendant] [data-tl-state~="cursor"])::after {
  content: "";
  position: absolute;
  inset: 0;
  z-index: var(--tl-layer-sticky);
  outline-offset: calc(-1 * var(--tl-focus-offset));
  pointer-events: none;
}

/* Dieselbe Fläche an der hervorgehobenen Option der Select-Liste (position: relative setzt select.css); abgerundet wie die Option. */
.tl-select__option[data-tl-state~="highlighted"]::after {
  content: "";
  position: absolute;
  inset: 0;
  border-radius: inherit;
  outline-offset: calc(-1 * var(--tl-focus-offset));
  pointer-events: none;
}

/* Der Behälter mit virtuellem Cursor zeichnet kein Browser-Outline (Spec 3b §3): der Ring liegt am
   Cursor-Element. Die einzige Ausnahme vom Ring, nur dieser Selektor. Ohne Cursor-Element setzt die
   Engine kein aria-activedescendant (WCAG 2.4.7) — dann gilt der normale Ring. */
:where(:not(input, textarea, [role="combobox"])[aria-activedescendant]):focus-visible {
  outline-style: none;
}

/* Icons: drei Stufen nach Rolle plus Glyph im Control — siehe skalen.md „Icons“.
   line-height 1, sonst erbt der Glyph die Zeilenhöhe des Fließtexts; das 1em-Quadrat hält
   Menü- und Baumspalten in Flucht. Die Fläche einer Icon-Schaltfläche ist Sache des Controls. */
.tl-icon-glyph, .tl-icon-sm, .tl-icon-md, .tl-icon-lg {
  line-height: 1;
  width: 1em;
  height: 1em;
  display: inline-block;
  text-align: center;
  flex-shrink: 0;
}
.tl-icon-glyph { font-size: var(--tl-size-icon-glyph); }
.tl-icon-sm { font-size: var(--tl-size-icon-sm); }
.tl-icon-md { font-size: var(--tl-size-icon-md); }
.tl-icon-lg { font-size: var(--tl-size-icon-lg); }

/* Sprungziel (<anchor>, scroll.ts): nach einem Sprung blitzt das Ziel kurz auf, damit der Sprung zu sehen ist — auch
   wenn nichts scrollt, weil das Ziel schon sichtbar war. Ein Zustand, keine Klasse; scroll.ts setzt und entfernt ihn.
   Das Bild ist der halo des Pakets (focus-width in surface-state-hover-strong), kein Ring: der Ring gehört der Tastatur
   (Spec 5d §3, Plan-Review K2). Der halo klingt zum eigenen Schatten des Ziels aus — ein Endbild „transparent“ wäre
   kein halo und bräche das Klassen-Gate. Reduced Motion regelt die Grundregel unten. */
[data-tl-anchor][data-tl-state~="flash"] {
  border-radius: var(--tl-radius-sm);
  animation: tl-anchor-flash var(--tl-duration-loop) var(--tl-easing-exit);
}

@keyframes tl-anchor-flash {
  from { box-shadow: 0 0 0 var(--tl-focus-width) var(--tl-surface-state-hover-strong); }
}

/* Wer Bewegung abbestellt hat, hat sie abbestellt. 0.01ms statt 0, sonst feuert transitionend nie. */
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }
}

/* Druck: rem hat im Druck keine Wurzel. Eigene Leiter in pt. */
@media print {
${print}
  .tl-print-title, .tl-print-heading, .tl-print-body, .tl-print-caption {
    font-variant-numeric: tabular-nums;
  }
}
`;
}

export function generate(P, T, components = []) {
  const R = resolve(P, T);
  return {
    'primitives.css': primitivesCss(P),
    'tokens.css': tokensCss(P, T, R),
    'base.css': baseCss(T),
    'components.css': componentsCss(components, T),
  };
}

if (typeof process !== 'undefined' && import.meta.url === `file://${process.argv[1]}`) {
  const { writeFileSync, mkdirSync } = await import('node:fs');
  const P = JSON.parse(readFileSync(new URL('../src/primitives.json', import.meta.url)));
  const T = JSON.parse(readFileSync(new URL('../src/tokens.json', import.meta.url)));
  // Zwei Ziele, derselbe Text: dist/ für Tests, Specimen und derive; der Webapp-Ordner des Moduls für die
  // Engine, die ihn als web-fragment.war packt (die Controls laden /style/tl-design-system/*.css von dort).
  const targets = [new URL('../dist/', import.meta.url), new URL('../src/main/webapp/style/tl-design-system/', import.meta.url)];
  for (const dir of targets) mkdirSync(dir, { recursive: true });
  const css = generate(P, T, componentSources(new URL('../src/components/', import.meta.url)));
  for (const [name, text] of Object.entries(css)) {
    for (const dir of targets) writeFileSync(new URL(name, dir), text);
    console.log(`geschrieben: dist/${name}, src/main/webapp/style/tl-design-system/${name}`);
  }
  writeFileSync(new URL('tokens.dtcg.json', targets[0]), JSON.stringify(dtcg(P, T), null, 2) + '\n');
  console.log('geschrieben: dist/tokens.dtcg.json');
}
