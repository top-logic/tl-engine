// Der Build schreibt jede erzeugte CSS-Datei zweimal: nach dist/ und nach src/main/webapp/style/tl-design-system/.
// Das zweite Ziel packt die Engine als web-fragment.war des Moduls; die Controls laden von dort. Beide müssen
// byte-gleich sein, keine trägt ein Siegel, jede beginnt mit der Kopfzeile des Generators.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const FILES = ['primitives.css', 'tokens.css', 'base.css', 'components.css'];
const HEADER = '/* Generated by com.top_logic.design.system (src/, tools/generate.mjs) during the build.';
const read = (rel) => readFileSync(new URL(rel, import.meta.url), 'utf8');

// Liest nur: node tools/generate.mjs (npm run build) läuft vorher, im Build in generate-resources. Er schreibt
// dist/ neu; ein Test, der das tut, ließe parallele Tests halb geschriebene Dateien lesen.
test('nach generate liegt jede CSS-Datei byte-gleich in dist/ und im Webapp-Ordner, ohne Siegel, mit Kopfzeile', () => {
  for (const f of FILES) {
    const dist = read(`../dist/${f}`);
    assert.equal(read(`../src/main/webapp/style/tl-design-system/${f}`), dist, `${f}: Webapp-Ordner weicht von dist/ ab — node tools/generate.mjs`);
    assert.ok(!dist.includes('sha256:'), `${f} trägt noch ein Siegel`);
    assert.ok(dist.startsWith(HEADER), `${f} beginnt nicht mit der Kopfzeile`);
  }
});
