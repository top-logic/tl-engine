package test.com.top_logic.layout.react;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import junit.framework.TestCase;

/**
 * Tests that the stylesheets of the design system package are the generated files, unchanged.
 *
 * <p>
 * The files under {@code style/tl-design-system} are generated in the repository {@code TopLogic/tl-design-system}
 * and copied here. Each ends with a seal: the SHA-256 of everything before it. A change made by hand in this copy
 * breaks the seal and fails here; the next publish of the package would silently drop it otherwise. A change belongs
 * into the package sources ({@code design-system/src}), then {@code node tools/generate.mjs} and
 * {@code node tools/publish-to-worktree.mjs}.
 * </p>
 */
public class TestDesignSystemCopy extends TestCase {

	private static final File DIR = new File("src/main/webapp/style/tl-design-system");

	private static final String[] FILES = { "primitives.css", "tokens.css", "base.css", "components.css" };

	private static final Pattern SEAL =
		Pattern.compile("/\\* tl-design-system sha256:([0-9a-f]{64}) [^\\n]*\\*/\\n$");

	/** Every copied stylesheet carries an intact seal. */
	public void testTheCopyIsTheGeneratedPackage() throws IOException, NoSuchAlgorithmException {
		for (String name : FILES) {
			File file = new File(DIR, name);
			assertTrue("Missing design system stylesheet: " + file, file.isFile());

			// A checkout on Windows may convert line ends; the seal is computed over LF.
			String text = Files.readString(file.toPath(), StandardCharsets.UTF_8).replace("\r\n", "\n");
			Matcher seal = SEAL.matcher(text);
			assertTrue(name + " has no seal: it is not a file generated by TopLogic/tl-design-system.", seal.find());

			String body = text.substring(0, seal.start());
			byte[] hash = MessageDigest.getInstance("SHA-256").digest(body.getBytes(StandardCharsets.UTF_8));
			assertEquals(name + " was changed by hand. Make the change in TopLogic/tl-design-system (design-system/src),"
				+ " then run node tools/generate.mjs and node tools/publish-to-worktree.mjs.",
				seal.group(1), HexFormat.of().formatHex(hash));
		}
	}

}
