	/**
	 * High-level overview using FULL two-truth-set mode with AvailableFactsGenerator.
	 * 
	 * This demonstrates the complete separation of required_facts and available_facts,
	 * with available_facts generated by calling ALL tools comprehensively.
	 * 
	 * This test is disabled by default - rename to enable it.
	 */
	public void testOverviewWithFullTwoTruthSet() {
		String prompt = "give me a high-level overview of the luigis.pizzashop model (types and relationships only)";
		List<String> allowedModules = List.of("luigis.pizzashop");
		boolean allowFramework = false;
		int minScore = 7;
		int judgeRuns = 3;

		// Build required facts (minimal - only types + relationships)
		ExpectedFactsBuilder builder = new ExpectedFactsBuilder();
		ExpectedFactsJsonBuilder requiredBuilder = new ExpectedFactsJsonBuilder(allowedModules, allowFramework);
		
		requiredBuilder.addAllowedFrameworkTypes(
			"tl.model:TLObject",
			"tl.core:String",
			"tl.core:Double",
			"tl.model:TLType"
		);
		
		requiredBuilder.enableRequiredSection();

		String typesJson = builder.getBrowserTool().listTypes("luigis.pizzashop");
		TypeListResponse typesResponse = builder.parseResponse(typesJson, TypeListResponse.class);
		requiredBuilder.markTypesAsRequired(typesResponse);
		requiredBuilder.addTypes(typesResponse);

		for (var type : typesResponse.getTypes()) {
			if ("class".equals(type.getMetaType())) {
				String partsJson = builder.getBrowserTool().listTypeParts("luigis.pizzashop", type.getName(), true);
				TypePartListResponse partsResponse = builder.parseResponse(partsJson, TypePartListResponse.class);
				requiredBuilder.markRelationshipsAsRequired(partsResponse);
				requiredBuilder.addRelationshipsFromParts(partsResponse);
			}
		}

		String requiredFactsJson = requiredBuilder.build();

		// Generate complete available facts (oracle - ALL tools)
		System.out.println("\nGenerating complete available facts (oracle dataset)...");
		AvailableFactsGenerator generator = new AvailableFactsGenerator();
		String availableFactsJson = generator.generateForModule("luigis.pizzashop", allowFramework);

		// Run test with both truth sets
		runScoringTestTwoTruthSet(prompt, requiredFactsJson, availableFactsJson, minScore, judgeRuns);
	}

	/**
	 * Helper method to run a scoring test with the given prompt and expected facts.
	 * This version uses the legacy single-truth-set mode (backward compatible).
	 */
	private void runScoringTest(String prompt, String expectedFactsJson, int minScore, int judgeRuns) {
		System.out.println("\n==========================================");
		System.out.println("Testing: " + prompt);
		System.out.println("==========================================");

		System.out.println("\nExpected Facts JSON (includes 'required' section if two-truth-set mode):");
		System.out.println(expectedFactsJson);
		
		// Parse and print sections separately for clarity
		if (expectedFactsJson.contains("\"required\"")) {
			System.out.println("\n[INFO] Using two-truth-set mode (has 'required' section)");
			System.out.println("[INFO] Judge will use 'required' for missing facts, full facts for hallucination detection");
		}

		// Run the agent
		ModelExplorerTool tool = new ModelExplorerTool();
		String actualAnswer = tool.exploreModel(prompt);

		System.out.println("\nActual Answer:");
		System.out.println(actualAnswer);

		// Judge the answer
		AiJudgeClient judge = new AiJudgeClient(AIService.getInstance());
		String judgeSystemPrompt = loadJudgeSystemPrompt();

		JudgeResult result;
		if (judgeRuns > 1) {
			result = judge.scoreAnswerWithMedian(expectedFactsJson, actualAnswer, judgeSystemPrompt, judgeRuns);
		} else {
			result = judge.scoreAnswer(expectedFactsJson, actualAnswer, judgeSystemPrompt);
		}

		// Print results
		printJudgeResult(result);

		// Assertions
		assertTrue(
			"Score must be at least " + minScore + " (was: " + result.getScore() + ")",
			result.getScore() >= minScore
		);

		assertTrue(
			"No incorrect claims allowed. Found: " + result.getIncorrectClaims(),
			result.getIncorrectClaims().isEmpty()
		);

		assertTrue(
			"No scope violations allowed. Found: " + result.getScopeViolations(),
			result.getScopeViolations().isEmpty()
		);
	}

	/**
	 * Helper method to run a scoring test with explicit two-truth-set mode.
	 * Prints both required_facts and available_facts separately for visibility.
	 */
	private void runScoringTestTwoTruthSet(
		String prompt,
		String requiredFactsJson,
		String availableFactsJson,
		int minScore,
		int judgeRuns
	) {
		System.out.println("\n==========================================");
		System.out.println("Testing: " + prompt);
		System.out.println("==========================================");

		System.out.println("\n[TWO-TRUTH-SET MODE]");
		
		System.out.println("\n--- Required Facts (prompt-specific minimum) ---");
		System.out.println(requiredFactsJson);
		
		System.out.println("\n--- Available Facts (complete oracle) ---");
		// Print abbreviated version if too long
		if (availableFactsJson.length() > 5000) {
			System.out.println(availableFactsJson.substring(0, 5000));
			System.out.println("\n... (truncated, total " + availableFactsJson.length() + " chars)");
		} else {
			System.out.println(availableFactsJson);
		}

		// Run the agent
		ModelExplorerTool tool = new ModelExplorerTool();
		String actualAnswer = tool.exploreModel(prompt);

		System.out.println("\n--- Actual Answer ---");
		System.out.println(actualAnswer);

		// Judge the answer
		AiJudgeClient judge = new AiJudgeClient(AIService.getInstance());
		String judgeSystemPrompt = loadJudgeSystemPrompt();

		JudgeResult result;
		if (judgeRuns > 1) {
			result = judge.scoreAnswerWithMedianTwoTruthSet(
				requiredFactsJson, availableFactsJson, actualAnswer, judgeSystemPrompt, judgeRuns);
		} else {
			result = judge.scoreAnswerTwoTruthSet(
				requiredFactsJson, availableFactsJson, actualAnswer, judgeSystemPrompt);
		}

		// Print results
		printJudgeResult(result);

		// Assertions
		assertTrue(
			"Score must be at least " + minScore + " (was: " + result.getScore() + ")",
			result.getScore() >= minScore
		);

		assertTrue(
			"No incorrect claims allowed. Found: " + result.getIncorrectClaims(),
			result.getIncorrectClaims().isEmpty()
		);

		assertTrue(
			"No scope violations allowed. Found: " + result.getScopeViolations(),
			result.getScopeViolations().isEmpty()
		);
	}

	/**
	 * Prints the judge result in a readable format.
	 */
	private void printJudgeResult(JudgeResult result) {
		System.out.println("\nJudge Result:");
		System.out.println("Score: " + result.getScore() + "/10");

		if (!result.getMissingFacts().isEmpty()) {
			System.out.println("Missing facts: " + result.getMissingFacts());
		}

		if (!result.getIncorrectClaims().isEmpty()) {
			System.out.println("Incorrect claims: " + result.getIncorrectClaims());
		}

		if (!result.getScopeViolations().isEmpty()) {
			System.out.println("Scope violations: " + result.getScopeViolations());
		}

		if (!result.getHallucinations().isEmpty()) {
			System.out.println("Hallucinations: " + result.getHallucinations());
		}

		if (!result.getNotFetched().isEmpty()) {
			System.out.println("Not fetched (claimed without tool evidence): " + result.getNotFetched());
		}

		if (!result.getFormatViolations().isEmpty()) {
			System.out.println("Format violations: " + result.getFormatViolations());
		}
	}

	/**
	 * Loads the default judge system prompt template.
	 */
	private String loadJudgeSystemPrompt() {
		try {
			return new String(Files.readAllBytes(
				Paths.get("src/test/resources/com/top_logic/ai/demo/judge-system-prompt.txt")
			));
		} catch (Exception ex) {
			throw new RuntimeException("Failed to load judge system prompt", ex);
		}
	}


	/**
	 * Creates the test suite with required service dependencies.
	 */
	public static Test suite() {
		return suite(ModelExplorerToolTest.class);
	}

	protected static Test suite(Class<? extends Test> test, BasicRuntimeModule<?>... additionalModules) {
		BasicRuntimeModule<?>[] modules = getModules(additionalModules);

		return KBSetup.getSingleKBTest(
			ServiceTestSetup.createSetup(
				new TestSuite(test),
				modules));
	}

	private static BasicRuntimeModule<?>[] getModules(BasicRuntimeModule<?>... additionalModules) {
		ArrayList<BasicRuntimeModule<?>> modules = new ArrayList<>();

		modules.add(ModelService.Module.INSTANCE);
		modules.add(LabelProviderService.Module.INSTANCE);
		modules.add(AIService.Module.INSTANCE);

		modules.addAll(Arrays.asList(additionalModules));

		return modules.toArray(new BasicRuntimeModule<?>[modules.size()]);
	}
