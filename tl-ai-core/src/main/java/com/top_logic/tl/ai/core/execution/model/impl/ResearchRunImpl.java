	public Long computeTokens() {
		AgentExecution lead = getExecution();
		if (lead == null) {
			return null;
		}
		long tokens = 0;
		Set<AgentExecution> seen = new HashSet<>();
		Deque<AgentExecution> open = new ArrayDeque<>();
		open.add(lead);
		while (!open.isEmpty()) {
			AgentExecution execution = open.remove();
			if (!seen.add(execution)) {
				continue;
			}
			tokens += AgentExecutionStore.usageOf(execution).totalTokens();
			for (TLObject child : execution.tReferers(TlAiExecutionFactory.getParentExecutionAgentExecutionAttr())) {
				if (child instanceof AgentExecution childExecution) {
					open.add(childExecution);
				}
			}
		}
		return Long.valueOf(tokens);
	}

