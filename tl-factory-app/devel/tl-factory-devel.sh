# Local development setup of tl-factory-app: Gitea and Jenkins of compose.yaml.
#
#   tl-factory-devel.sh [up]   start (and set up on the first start), print the settings of tl-factory-app
#   tl-factory-devel.sh down   stop and remove the containers, keep the data
#   tl-factory-devel.sh reset  remove containers, data and the generated credentials
#
# The setup creates the Gitea administrator, the organization of the project repositories, an
# access token for the control application and a read token for Jenkins, and the Jenkins
# administrator with an API token. The credentials are generated and written to the secret folder of
# the developer (tl_devel_secrets_dir, default ~/.top-logic/secrets), where the control application
# reads tl_factory_gitea_token and tl_factory_jenkins_token. The folder also gets the key of the
# database secret store of the control application, tl_secret_store_key, if it has none; it is
# never replaced or removed, since the access tokens the tenants entered are unreadable without it.
# See the developer article factory/index, section "Local setup".

set -eu

cd "$(dirname "$0")"

GITEA_PORT="${TL_FACTORY_DEVEL_GITEA_PORT:-3300}"
JENKINS_PORT="${TL_FACTORY_DEVEL_JENKINS_PORT:-8380}"
GITEA_URL="http://localhost:${GITEA_PORT}/"
JENKINS_URL="http://localhost:${JENKINS_PORT}/"
# The defaults of tl_factory_gitea_owner and tl_factory_jenkins_user of the control application.
GITEA_ADMIN=factory-admin
GITEA_ORG=tl-factory
JENKINS_ADMIN=tl-factory
SCM_CREDENTIALS=tl-factory-gitea

SECRETS="${tl_devel_secrets_dir:-${HOME}/.top-logic/secrets}"
GITEA_TOKEN_FILE="${SECRETS}/tl_factory_gitea_token"
JENKINS_TOKEN_FILE="${SECRETS}/tl_factory_jenkins_token"
SECRET_STORE_KEY_FILE="${SECRETS}/tl_secret_store_key"
# Scopes of the access token of the control application, see the developer article factory/git-hosting.
GITEA_TOKEN_SCOPES=write:organization,write:repository,read:user
# The credentials of this setup only: Gitea, and Jenkins as environment of its container.
GITEA_STATE="${SECRETS}/tl_factory_devel_gitea.env"
JENKINS_STATE="${SECRETS}/tl_factory_devel_jenkins.env"

random_hex() {
	od -An -tx1 -N16 /dev/urandom | tr -d ' \n'
}

# A random AES key of 256 bits in Base64.
random_key() {
	head -c 32 /dev/urandom | base64 | tr -d '\n'
}

# Writes a file readable by the developer only.
write_secret() {
	(umask 077 && printf '%s' "$2" > "$1")
}

# Writes a secret of the control application, unless the file holds a value not generated here.
write_app_secret() {
	if [ -f "$1" ] && [ "$(cat "$1")" != "$2" ] && [ "$(cat "$1")" != "${3:-}" ]; then
		echo "$1 holds a value not generated by this setup; move it away and start again." >&2
		exit 1
	fi
	write_secret "$1" "$2"
}

gitea() {
	docker compose exec -T -u git gitea gitea "$@"
}

api_status() {
	curl -s -o /dev/null -w '%{http_code}' "$@"
}

await() {
	what="$1"
	shift
	i=0
	until [ "$(api_status "$@")" = 200 ]; do
		i=$((i + 1))
		if [ "$i" -gt 300 ]; then
			echo "${what} did not start." >&2
			exit 1
		fi
		sleep 1
	done
}

up() {
	mkdir -p "${SECRETS}"
	chmod 700 "${SECRETS}"

	if [ ! -f "${SECRET_STORE_KEY_FILE}" ]; then
		write_secret "${SECRET_STORE_KEY_FILE}" "$(random_key)"
	fi

	GITEA_PASSWORD=
	GITEA_TOKEN=
	GITEA_READ_TOKEN=
	if [ -f "${GITEA_STATE}" ]; then
		. "${GITEA_STATE}"
	fi
	OLD_GITEA_TOKEN="${GITEA_TOKEN}"

	docker compose up -d gitea
	await Gitea "${GITEA_URL}api/v1/version"

	if ! gitea admin user list --admin | awk -v name="${GITEA_ADMIN}" '$2 == name { found = 1 } END { exit !found }'; then
		GITEA_PASSWORD="$(random_hex)"
		gitea admin user create --username "${GITEA_ADMIN}" --password "${GITEA_PASSWORD}" \
			--email "${GITEA_ADMIN}@localhost" --admin --must-change-password=false >/dev/null
		GITEA_TOKEN=
		GITEA_READ_TOKEN=
	elif [ -z "${GITEA_PASSWORD}" ]; then
		GITEA_PASSWORD="$(random_hex)"
		gitea admin user change-password --username "${GITEA_ADMIN}" --password "${GITEA_PASSWORD}" \
			--must-change-password=false >/dev/null
	fi
	if [ "$(api_status -u "${GITEA_ADMIN}:${GITEA_PASSWORD}" "${GITEA_URL}api/v1/orgs/${GITEA_ORG}")" != 200 ]; then
		curl -fsS -o /dev/null -u "${GITEA_ADMIN}:${GITEA_PASSWORD}" -H 'Content-Type: application/json' \
			-d "{\"username\": \"${GITEA_ORG}\"}" "${GITEA_URL}api/v1/orgs"
	fi
	# A token without one of the scopes (an older setup lacks read:user) is replaced.
	if [ -z "${GITEA_TOKEN}" ] || [ "$(api_status -H "Authorization: token ${GITEA_TOKEN}" \
			"${GITEA_URL}api/v1/orgs/${GITEA_ORG}")" != 200 ] || [ "$(api_status \
			-H "Authorization: token ${GITEA_TOKEN}" "${GITEA_URL}api/v1/user")" != 200 ]; then
		GITEA_TOKEN="$(gitea admin user generate-access-token --username "${GITEA_ADMIN}" \
			--token-name "tl-factory-$(date +%s)" --scopes "${GITEA_TOKEN_SCOPES}" --raw)"
	fi
	# Jenkins only clones.
	if [ -z "${GITEA_READ_TOKEN}" ] || [ "$(api_status -H "Authorization: token ${GITEA_READ_TOKEN}" \
			"${GITEA_URL}api/v1/orgs/${GITEA_ORG}")" != 200 ]; then
		GITEA_READ_TOKEN="$(gitea admin user generate-access-token --username "${GITEA_ADMIN}" \
			--token-name "jenkins-$(date +%s)" --scopes read:organization,read:repository --raw)"
	fi
	write_secret "${GITEA_STATE}" "GITEA_PASSWORD=${GITEA_PASSWORD}
GITEA_TOKEN=${GITEA_TOKEN}
GITEA_READ_TOKEN=${GITEA_READ_TOKEN}
"
	write_app_secret "${GITEA_TOKEN_FILE}" "${GITEA_TOKEN}" "${OLD_GITEA_TOKEN}"

	TL_JENKINS_ADMIN_PASSWORD="$(random_hex)"
	TL_JENKINS_API_TOKEN="11$(random_hex)"
	if [ -f "${JENKINS_STATE}" ]; then
		. "${JENKINS_STATE}"
	fi
	write_secret "${JENKINS_STATE}" "TL_JENKINS_ADMIN=${JENKINS_ADMIN}
TL_JENKINS_ADMIN_PASSWORD=${TL_JENKINS_ADMIN_PASSWORD}
TL_JENKINS_API_TOKEN=${TL_JENKINS_API_TOKEN}
TL_JENKINS_SCM_CREDENTIALS_ID=${SCM_CREDENTIALS}
TL_JENKINS_SCM_USER=${GITEA_ADMIN}
TL_JENKINS_SCM_PASSWORD=${GITEA_READ_TOKEN}
"
	write_app_secret "${JENKINS_TOKEN_FILE}" "${TL_JENKINS_API_TOKEN}"

	# Created anew, so that it gets a changed read token.
	docker compose up -d --build --force-recreate jenkins
	await Jenkins -u "${JENKINS_ADMIN}:${TL_JENKINS_API_TOKEN}" "${JENKINS_URL}api/json"

	cat <<EOF

Gitea:   ${GITEA_URL} (user ${GITEA_ADMIN}, password ${GITEA_PASSWORD})
Jenkins: ${JENKINS_URL} (user ${JENKINS_ADMIN}, password ${TL_JENKINS_ADMIN_PASSWORD})
Tokens:  ${GITEA_TOKEN_FILE}, ${JENKINS_TOKEN_FILE}
Key of the secret store: ${SECRET_STORE_KEY_FILE}

Environment of tl-factory-app:
  export tl_factory_gitea_url=${GITEA_URL}
  export tl_factory_jenkins_url=${JENKINS_URL}
  export tl_factory_jenkins_scm_credentials=${SCM_CREDENTIALS}
EOF
}

down() {
	docker compose down
}

reset() {
	docker compose down --volumes --rmi local
	GITEA_TOKEN=
	if [ -f "${GITEA_STATE}" ]; then
		. "${GITEA_STATE}"
	fi
	if [ -f "${GITEA_TOKEN_FILE}" ] && [ "$(cat "${GITEA_TOKEN_FILE}")" = "${GITEA_TOKEN}" ]; then
		rm "${GITEA_TOKEN_FILE}"
	fi
	TL_JENKINS_API_TOKEN=
	if [ -f "${JENKINS_STATE}" ]; then
		. "${JENKINS_STATE}"
	fi
	if [ -f "${JENKINS_TOKEN_FILE}" ] && [ "$(cat "${JENKINS_TOKEN_FILE}")" = "${TL_JENKINS_API_TOKEN}" ]; then
		rm "${JENKINS_TOKEN_FILE}"
	fi
	rm -f "${GITEA_STATE}" "${JENKINS_STATE}"
}

case "${1:-up}" in
	up) up ;;
	down) down ;;
	reset) reset ;;
	*)
		echo "Usage: $0 [up|down|reset]" >&2
		exit 2
		;;
esac
